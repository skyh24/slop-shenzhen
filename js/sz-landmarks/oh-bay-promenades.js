// 转角两侧取同一对截点，地表裁切后只覆盖陆地，不另设接触高度。
export function promenadePatches(side) {
  return paths[side].map(({ sourceId, points }) => {
    const normals = points.slice(1).map(([x, z], i) => {
      const dx = x - points[i][0], dz = z - points[i][1], length = Math.hypot(dx, dz);
      return { x: -dz / length, z: dx / length };
    });
    const left = [], right = [];
    for (const [i, [x, z]] of points.entries()) {
      const a = normals[i - 1] ?? normals[0], b = normals[i] ?? a;
      const scale = 2 / (1 + a.x * b.x + a.z * b.z);
      const dx = (a.x + b.x) * scale, dz = (a.z + b.z) * scale;
      left.push({ x: x + dx, z: z + dz });
      right.push({ x: x - dx, z: z - dz });
    }
    return { sourceId, ring: [...left, ...right.reverse()], style: 'sportsApron' };
  });
}
